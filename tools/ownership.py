# -*- coding: utf-8 -*-
"""How much of Lume is still Hume Launcher's? Clones Hume (Apache-2.0) to a temporary folder, compares every Java file of
lume/src by its code lines (no package, import or comment lines), and writes docs/OWNERSHIP.md.
Run: python3 tools/ownership.py        The goal of the rewrite is to take the last column to zero, one file at a time."""
import os, re, difflib, subprocess, tempfile, datetime
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(HERE, "..")
UP = "https://github.com/petrobot-admin/hume-launcher"
tmp = tempfile.mkdtemp(prefix="hume_")
subprocess.run(["git", "clone", "-q", "--depth", "1", UP, tmp], check=True)
def files(root):
    d = {}
    for dp, _, fs in os.walk(root):
        for f in fs:
            if f.endswith(".java"): d.setdefault(f, os.path.join(dp, f))
    return d
norm = lambda t: [re.sub(r"\s+", " ", l).strip() for l in t.splitlines() if l.strip() and not l.strip().startswith(("package", "import", "//", "*", "/*"))]
U = files(tmp); M = files(os.path.join(ROOT, "lume", "src"))
# Files known to come from other projects (their own licences, credited in NOTICE)
THIRD = {"QrCode.java": "Project Nayuki, MIT", "ControlPanelOverlay.java": "adapted from tvOS Launcher, Apache-2.0", "RecentAppsOverlay.java": "adapted from tvOS Launcher, Apache-2.0"}
rows, tot, same = [], 0, 0
for f, p in sorted(M.items()):
    a = norm(open(p, encoding="utf-8", errors="ignore").read()); tot += len(a)
    if f in U and f not in THIRD:
        b = norm(open(U[f], encoding="utf-8", errors="ignore").read())
        k = sum(m.size for m in difflib.SequenceMatcher(None, b, a, autojunk=False).get_matching_blocks()); same += k
        rows.append((f, len(a), k, "Hume"))
    elif f in THIRD: rows.append((f, len(a), 0, THIRD[f]))
    else: rows.append((f, len(a), 0, "ours"))
rows.sort(key=lambda r: -r[2])
out = ["# Ownership of Lume's code", "", "Generated by `tools/ownership.py` on %s. Lines are code lines (no imports, package or comments). *Identical to Hume* counts lines that match Hume Launcher's file of the same name; it is the number the rewrite brings down." % datetime.date.today(), "",
       "**Lume today: %d code lines, %d (%.0f%%) identical to Hume Launcher (Apache-2.0).**" % (tot, same, 100.0 * same / max(1, tot)), "",
       "| File | Lines | Identical to Hume | Origin |", "|---|---|---|---|"]
for f, n, k, o in rows: out.append("| %s | %d | %d (%.0f%%) | %s |" % (f, n, k, 100.0 * k / max(1, n), o))
out += ["", "## How a file becomes ours", "", "1. Write down what the file does (its behaviour and its inputs), not how Hume does it.", "2. Write it again from that description, without Hume's file open.", "3. Check it on the TV with the screens tool (`lume/tools/screens.sh`) and the phone remote.", "4. Run this script: the row drops to ours.", "", "Until a file is rewritten it keeps Hume's notice (see `lume/NOTICE`)."]
open(os.path.join(ROOT, "docs", "OWNERSHIP.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
print("lines %d identical %d (%.1f%%)" % (tot, same, 100.0 * same / max(1, tot)))
subprocess.run(["rm", "-rf", tmp])
